; MIDI synthesizer.

; Register definitions.
.include "tn25def.inc"

; Sentinel value for unset midi byte.
.equ empty = 0xff

; MIDI instrument number.
.def instrument = r24

; 4-bit pitch bend.
.def bend = r25

; Voice 0.
.def p0l = r0
.def p0h = r1
.def f0l = r2
.def f0h = r3
.def n0 = r4
.def v0 = r5

; Voice 1.
.def p1l = r6
.def p1h = r7
.def f1l = r8
.def f1h = r9
.def n1 = r10
.def v1 = r11

; Voice 2.
.def p2l = r12
.def p2h = r13
.def f2l = r14
.def f2h = r15
.def n2 = r16
.def v2 = r17

; Voice 3.
.def p3l = r18
.def p3h = r19
.def f3l = r20
.def f3h = r21
.def n3 = r22
.def v3 = r23

; Initialize the registers for the given voice.
.macro voice_init
    clr @0
    clr @1
    clr @2
    clr @3
    clr @4
    clr @5
.endm

; Output one synth voice in exactly 10 cycles.
.macro voice_10
    ldi YL, 0x80
    add @0, @2
    adc @1, @3
    cp @0, XL
    cpc @1, XH
    brge one_%
    sub YL, @4
    rjmp voice_%
one_%:
    add YL, @4
    nop
voice_%:
    out OCR1B, YL
.endm

; Output one synth voice in exactly 16 cycles.
.macro voice
    voice_10 @0, @1, @2, @3, @4
    nop
    nop
    nop
    nop
    nop
    nop
.endm

; Set velocity to 0 if the pitch matches.
.macro note_off
    cp @0, ZL
    brne note_off_end_%
    clr @1
note_off_end_%:
.endm

; Update frequency based on pitch bend.
.macro pitch_bend
    push ZL
    push ZH
    ldi ZL, low(frequency)
    ldi ZH, high(frequency)
    mov XL, @2
    rcall update_note
    lpm @0, Z+
    lpm @1, Z
    pop ZH
    pop ZL
.endm

; Program start
.org 0x000
    rjmp reset

; Pin change interrupt
.org 0x0002
    sbic PINB, 0
    reti
    push YL
    in YL, SREG
    push YL
    ldi YL, 1 << PCIE
    out GIMSK, YL
    ldi YL, (1 << USIOIF) | 8
    out USISR, YL
    ldi YL, 224
    out TCNT0, YL
    ldi YL, 1 << CS00
    out TCCR0B, YL
    pop YL
    out SREG, YL
    pop YL
    reti
    
; Initialization.
reset:
    ldi YL, low(RAMEND)
    out SPL, YL
    ldi YL, 1 << PLLE
    out PLLCSR, YL
; Wait for PWM clock to stabilize.
wait_pll:
    in YL, PLLCSR
    sbrs YL, PLOCK
    rjmp wait_pll
    sbr YL, PCKE
    out PLLCSR, YL
    sbi DDRB, 4
    ldi YL, (1 << PWM1B) | (1 << COM1B1)
    out TCCR1, YL
    ldi YL, 0x80
    out OCR1B, YL
    sbi PORTB, 0
    ldi YL, 1 << PCIE
    out GIMSK, YL
    sbi PCMSK, PCINT0
    ldi YL, (1 << USIWM0) | (1 << USICS0)
    out USICR, YL
    ldi YL, 1 << USIOIF
    out USISR, YL
    ldi YL, 31
    out OCR0A, YL
    ldi YL, 1 << WGM01
    out TCCR0A, YL
    clr YL
    ldi instrument, 0x7f
    clr bend
    clr XL
    clr XH
    ldi ZL, empty
    ldi ZH, empty
    voice_init p0l, p0h, f0l, f0h, n0, v0
    voice_init p1l, p1h, f1l, f1h, n1, v1
    voice_init p2l, p2h, f2l, f2h, n2, v2
    voice_init p3l, p3h, f3l, f3h, n3, v3
    sei
; Check for midi byte.
main:
    in YL, USISR
    sbrs YL, USIOIF
    rjmp synth
    clr YL
    out TCCR0B, YL
    ldi YL, 1 << USIOIF
    out USISR, YL
    ldi YL, 1 << PCIE
    out GIMSK, YL
    push XL
    push XH
    cpi ZL, empty
    breq buf0_update
    cpi ZH, empty
    breq buf1_update
    in YL, USIBR
    rjmp parse_midi
; Add the byte to the end of the midi buffer.
buf0_update:
    in ZL, USIBR
    rjmp parse_midi
; Add the byte to the end of the midi buffer.
buf1_update:
    in ZH, USIBR
; Deserialize the midi message.
parse_midi:
    cpi ZL, 0xc0
    breq program_change
    cpi ZL, 0x80
    breq note_off
    cpi ZL, 0xe0
    breq pitch_bend
    cpi ZL, 0x90
    breq parse_midi_note_on
    rjmp midi_clr
parse_midi_note_on:
    rjmp note_on
; Handle instrument change message.
program_change:
    cpi ZH, empty
    breq midi_done
    ldi instrument, 0x7f
    in YL, USIBR
    sub instrument, YL
    rjmp midi_clr
; Handle note_off message.
note_off:
    cpi YL, empty
    breq midi_done
    note_off n0, v0
    note_off n1, v1
    note_off n2, v2
    note_off n3, v3
    rjmp midi_clr
; Restore registers.
midi_done:
    pop XH
    pop XL
    rjmp synth
; Handle pitch bend message.
pitch_bend:
    cpi YL, empty
    breq midi_done
    mov bend, ZH
    lsr bend
    lsr bend
    lsr bend
    subi bend, 8
    pitch_bend f0l, f0h, n0
    pitch_bend f1l, f1h, n1
    pitch_bend f2l, f2h, n2
    pitch_bend f3l, f3h, n3
    rjmp midi_clr
; Handle note_on message.
note_on:
    cpi YL, empty
    breq midi_done
    tst n0
    breq note_on_0
    cp ZL, n0
    breq note_on_0
    tst n1
    breq note_on_1
    cp ZL, n1
    breq note_on_1
    tst n2
    breq note_on_2
    cp ZL, n2
    breq note_on_2
    mov n3, ZH
    mov v3, YL
    pitch_bend f3l, f3h, n3
    rjmp midi_clr
; Overwrite voice 0
note_on_0:
    mov n0, ZH
    mov v0, YL
    pitch_bend f0l, f0h, n0
    rjmp midi_clr
; Overwrite voice 1.
note_on_1:
    mov n1, ZH
    mov v1, YL
    pitch_bend f1l, f1h, n1
    rjmp midi_clr
; Overwrite voice 2.
note_on_2:
    mov n2, ZH
    mov v2, YL
    pitch_bend f2l, f2h, n2
; Empty midi buffer.
midi_clr:
    ldi ZL, empty
    ldi ZH, empty
    rjmp midi_done
; Output pwm.
synth:
    voice p0l, p0h, f0l, f0h, v0
    voice p1l, p1h, f1l, f1h, v1
    voice_10 p2l, p2h, f2l, f2h, v2
    clr YL
    add XL, instrument
    adc XH, YL
    nop
    nop
    nop
    voice_10 p3l, p3h, f3l, f3h, v3
    rjmp main

; Get the frequency for the given pitch.
update_note:
    clr YL
    clr XH
    sbrc XL, 7
    sbr XH, 1
    sbrc XL, 6
    sbr XH, 0
    lsl XL
    lsl XL
    add XL, bend
    adc XH, YL
    add ZL, XL
    adc ZH, XH
    ret

